/**
 * Writes the starting store data (the same content as prisma/seed.ts) as a SQL
 * migration for Netlify Database, which applies it once, automatically:
 *
 *   npx tsx scripts/seed-to-sql.ts > netlify/database/migrations/<ts>_starting_data/migration.sql
 *
 * Every payment method is disabled, every delivery area inactive with no fee,
 * collections and FAQ entries unpublished, policy pages flagged for owner
 * review. No users, products, reviews or contact details. Rows use fixed IDs
 * and ON CONFLICT DO NOTHING, so applying it twice changes nothing.
 */

import { DEFAULT_PAYMENT_METHODS } from "../src/lib/payments/defaults";
import { slugify } from "../src/lib/text";
import { CATEGORIES, COLLECTIONS, DELIVERY_AREAS, HOME_SECTIONS, TAG_GROUPS } from "../prisma/seed-content/catalog";
import { POLICY_PAGES } from "../prisma/seed-content/pages";
import { FAQ_ITEMS } from "../prisma/seed-content/faq";

type Value = string | number | boolean | null | Record<string, unknown> | { raw: string };

function lit(value: Value): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  if ("raw" in value && typeof value.raw === "string") return value.raw;
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

const NOW = { raw: "CURRENT_TIMESTAMP" };
const lines: string[] = ["-- Souvenir Galore: starting store data, generated by scripts/seed-to-sql.ts", ""];

function insert(table: string, row: Record<string, Value>) {
  const cols = Object.keys(row);
  lines.push(`INSERT INTO "${table}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES (${cols.map((c) => lit(row[c])).join(", ")}) ON CONFLICT DO NOTHING;`);
}

// Categories (same slug rules as prisma/seed.ts)
lines.push("-- Categories");
const used = new Set<string>();
CATEGORIES.forEach((category, position) => {
  const id = `seed-cat-${position}`;
  const slug = slugify(category.name);
  used.add(slug);
  insert("Category", { id, name: category.name, slug, description: category.description, position, isPublished: true, showInNav: true, updatedAt: NOW });
  category.children.forEach((child, childPosition) => {
    let childSlug = slugify(child);
    if (used.has(childSlug)) childSlug = `${slugify(category.name, 30)}-${childSlug}`;
    used.add(childSlug);
    insert("Category", { id: `${id}-${childPosition}`, name: child, slug: childSlug, parentId: id, position: childPosition, isPublished: true, showInNav: true, updatedAt: NOW });
  });
});

lines.push("", "-- Filter groups and tags");
TAG_GROUPS.forEach((group, position) => {
  const groupId = `seed-tg-${group.slug}`;
  insert("TagGroup", { id: groupId, name: group.name, slug: group.slug, position, isFilterable: true, updatedAt: NOW });
  group.tags.forEach((name, tagPosition) => insert("Tag", { id: `${groupId}-${tagPosition}`, groupId, name, slug: slugify(name, 60), position: tagPosition }));
});

lines.push("", "-- Collections (unpublished)");
COLLECTIONS.forEach((collection, position) => {
  insert("Collection", { id: `seed-col-${position}`, name: collection.name, slug: slugify(collection.name), kind: collection.kind, description: collection.description, position, isPublished: false, updatedAt: NOW });
});

lines.push("", "-- Payment methods (ALL DISABLED, no account details)");
for (const method of DEFAULT_PAYMENT_METHODS) {
  insert("PaymentMethod", {
    id: `seed-pm-${method.code}`,
    code: method.code,
    type: method.type,
    name: method.name,
    description: method.description,
    instructions: method.instructions,
    isEnabled: false,
    requiresManualVerification: method.requiresManualVerification,
    allowCustomerReference: method.allowCustomerReference,
    availableForDelivery: method.availableForDelivery,
    availableForPickup: method.availableForPickup,
    position: method.position,
    config: method.config,
    updatedAt: NOW,
  });
}

lines.push("", "-- Delivery areas (inactive, fee to be set by the owner)");
DELIVERY_AREAS.forEach((name, position) => insert("DeliveryZone", { id: `seed-zone-${position}`, name, fee: 0, isActive: false, position, updatedAt: NOW }));

lines.push("", "-- Homepage sections");
HOME_SECTIONS.forEach((section, position) => {
  const id = `seed-home-${position}`;
  insert("HomeSection", {
    id,
    type: section.type,
    title: section.title ?? null,
    subtitle: section.subtitle ?? null,
    body: section.body ?? null,
    ctaLabel: section.ctaLabel ?? null,
    ctaHref: section.ctaHref ?? null,
    secondaryCtaLabel: section.secondaryCtaLabel ?? null,
    secondaryCtaHref: section.secondaryCtaHref ?? null,
    config: section.config ?? {},
    isVisible: section.isVisible ?? true,
    position,
    updatedAt: NOW,
  });
  (section.items ?? []).forEach((item, i) => insert("HomeSectionItem", { id: `${id}-${i}`, sectionId: id, title: item.title, body: item.body ?? null, position: i }));
});

lines.push("", "-- Policy pages (flagged for owner review)");
POLICY_PAGES.forEach((page, position) => {
  insert("Page", { id: `seed-page-${page.slug}`, slug: page.slug, title: page.title, body: page.body, footerGroup: page.footerGroup, showInFooter: page.showInFooter, isPublished: page.isPublished, position, needsOwnerReview: true, updatedAt: NOW });
});

lines.push("", "-- FAQ drafts (unpublished)");
FAQ_ITEMS.forEach((item, position) => insert("FaqItem", { id: `seed-faq-${position}`, question: item.question, answer: item.answer, category: item.category, position, isPublished: false, updatedAt: NOW }));

console.log(lines.join("\n"));
